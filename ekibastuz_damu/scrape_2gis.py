def _digits(code):
    return code.replace(".", "")

def _in(code, lst):
    d = _digits(code)
    return any(d.startswith(_digits(c)) for c, *_ in lst)

def programs_for(code):
    out = []
    if _in(code, ISKER) and not _in(code, ISKER_EXCL):
        out.append(P_ISKER)
    if _in(code, ISKER_MIO):
        out.append(P_ISKER_MIO)
    if _in(code, ORLEU) and not _in(code, ORLEU_EXCL):
        out.append(P_ORLEU)
    return out

