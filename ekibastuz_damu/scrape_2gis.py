def rubric_names(it):
    rs = it.get("rubrics") or []
    rs = sorted(rs, key=lambda r: 0 if r.get("kind") == "primary" else 1)
    return [r.get("name", "") for r in rs if r.get("name")]


def match(it):
    for rn in rubric_names(it):
        low = rn.lower()
        for m in RUBRIC_MAP:
            if re.search(m[2], low):
                return rn, m
    return None, None


def wa_link(it):
    """Первая ссылка WhatsApp в виде https://wa.me/<номер> (без шаблонного текста 2ГИС)."""
    for g in it.get("contact_groups") or []:
        for c in g.get("contacts") or []:
            if c.get("type") == "whatsapp":
                d = re.sub(r"\D", "", re.sub(r"\?.*", "", c.get("url") or "") or c.get("value") or "")
                if not d:
                    d = re.sub(r"\D", "", c.get("value") or c.get("text") or "")
                if d:
                    return f"https://wa.me/{d}"
    return ""


def contacts(it):
    phones, extra = [], []
    for g in it.get("contact_groups") or []:
        for c in g.get("contacts") or []:
            t = c.get("type")
            v = c.get("text") or c.get("value") or c.get("url") or ""
            if t == "phone":
                v = c.get("text") or c.get("value") or ""
                if v and v not in phones:
                    phones.append(v)
            elif t in ("website", "instagram"):  # WhatsApp — в отдельной колонке
                if t == "website":
                    v = c.get("text") or c.get("value") or ""
                elif t == "instagram" and (c.get("url") or "").startswith("http"):
                    v = c["url"]
                elif t == "whatsapp" and c.get("value"):
                    v = c["value"]
                if v:
                    lab = {"whatsapp": "WhatsApp", "website": "сайт", "instagram": "Instagram"}[t]
                    s = f"{lab}: {v}"
                    if s not in extra:
                        extra.append(s)
    return ", ".join(phones), "; ".join(extra)


def address(it):
    a = it.get("address_name") or ""
    if not a:
        a = it.get("full_address_name") or it.get("full_name") or ""
    comment = it.get("address_comment")
    return f"{a} ({comment})" if a and comment else a


NAME_EXCLUDE = re.compile(r"магазин|супермаркет|маркет|бутик|киоск|павильон|рынок|склад-магазин", re.I)


def firm_row(k, it):
    """Строка листа «Фирмы» или None, если фирма не подходит."""
    if not in_ekibastuz(it):
        return None
    if NAME_EXCLUDE.search(it.get("name") or ""):
        return None  # розничные магазины — не производство/услуга из перечня
    rn, m = match(it)
    if not m:
        return None
    progs = programs_for(m[3])
    if not progs:
        return None
    tel, extra = contacts(it)
    return [(it.get("name") or "").strip(), rn, f"{m[3]} {m[4]}", ", ".join(progs),
            address(it), tel, wa_link(it), extra, f"{BASE}/firm/{k}"]


def build_firms(items):
    rows, seen = [], set()
    for k, it in items.items():
        r = firm_row(k, it)
        if not r:
            continue
        key = (r[0].lower(), r[4].lower())
        if key in seen:
            continue
        seen.add(key)
        rows.append(r)
    rows.sort(key=lambda r: (r[3], r[1], r[0].lower()))
    return rows

