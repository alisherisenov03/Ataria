def keep_awake():
    """Windows: не уходить в сон, пока идёт сбор (перезагрузку обновлений это не отменяет)."""
    try:
        import ctypes
        ctypes.windll.kernel32.SetThreadExecutionState(0x80000000 | 0x00000001)
    except Exception:
        pass


def scrape(max_pages):
    """Как в interlark/parser-2gis: поиск открывается один раз, фирмы открываются
    кликом (страница не перезагружается), картинки/карта/аналитика заблокированы,
    страницы листаются кликом по номеру."""
    from playwright.sync_api import sync_playwright
    items = {}
    if RAW.exists():
        items = json.loads(RAW.read_text(encoding="utf-8"))
        print(f"Продолжаю: в {RAW.name} уже {len(items)} фирм")
    live = Live(items)
    print(f"Подходящие фирмы пишутся сразу в {LIVE.name}")
    queries = []
    for m in RUBRIC_MAP:
        for q in m[1]:
            if q not in queries:
                queries.append(q)

    keep_awake()
    with sync_playwright() as pw:
        br = launch(pw)
        ctx = br.new_context(locale="ru-RU", viewport={"width": 1400, "height": 900})
        ctx.route("**/*", lambda r: r.abort() if (
            r.request.resource_type in ("image", "media", "font") or BLOCK_RX.search(r.request.url)
        ) else r.continue_())
        page = ctx.new_page()
        listed = {}  # краткие данные фирм из выдачи (для отсева по рубрике до клика)

        def on_resp(r):
            u = r.url
            if "catalog.api.2gis" not in u or "/items" not in u or "byid" in u:
                return
            try:
                its = ((r.json() or {}).get("result") or {}).get("items") or []
            except Exception:
                return
            for i in its:
                if isinstance(i, dict) and i.get("id"):
                    listed[base_id(i["id"])] = i

        page.on("response", on_resp)

        def firm_links():
            out = []
            for a in page.query_selector_all("a[href*='/firm/']"):
                m = FIRM_HREF.search(a.get_attribute("href") or "")
                if m and m.group(1) not in [x[0] for x in out]:
                    out.append((m.group(1), a))
            return out

        def worth_click(fid):
            if fid in items:
                return False
            li = listed.get(fid)
            if li and li.get("rubrics"):
                if li.get("adm_div") and not in_ekibastuz(li):
                    return False
                return match(li)[1] is not None
            return True  # нет данных из выдачи — открываем карточку

        def run_query(q):
            got = 0
            page.goto(f"{BASE}/search/{q}", wait_until="domcontentloaded", timeout=60000)
            wait_captcha(page)
            for pn in range(1, max_pages + 1):
                try:
                    page.wait_for_selector("a[href*='/firm/']", timeout=8000)
                except Exception:
                    break  # нет результатов
                time.sleep(0.5)
                for fid, a in firm_links():
                    if not worth_click(fid):
                        continue
                    try:
                        with page.expect_response(lambda r: "/items/byid" in r.url, timeout=8000) as ri:
                            a.click()
                        res = ((ri.value.json() or {}).get("result") or {}).get("items") or []
                    except Exception:
                        wait_captcha(page)
                        res = []
                    it = next((x for x in res if base_id(x.get("id", "")) == fid), None) or listed.get(fid)
                    if it:
                        it["_query"] = q
                        items[fid] = it
                        got += 1
                        live.add(fid, it)
                    time.sleep(random.uniform(0.1, 0.25))
                nxt = page.query_selector(f"a[href*='/page/{pn + 1}']")
                if not nxt:
                    break
                old = {f for f, _ in firm_links()}
                nxt.click()
                for _ in range(40):  # ждём, пока выдача сменится
                    time.sleep(0.25)
                    if {f for f, _ in firm_links()} - old:
                        break
            return got

        t0 = time.time()
        done = set(json.loads(DONE.read_text(encoding="utf-8"))) if DONE.exists() else set()
        if done:
            print(f"Уже пройдено запросов: {len(done)} из {len(queries)} — пропускаю их")
        for qi, q in enumerate(queries, 1):
            if q in done:
                continue
            got = None
            for attempt in (1, 2):  # при сбое (обрыв сети, таймаут) — ещё одна попытка
                try:
                    got = run_query(q)
                    break
                except Exception as e:
                    print(f"   ! {q}: сбой ({str(e).splitlines()[0][:80]}), попытка {attempt}/2", flush=True)
                    time.sleep(3)
            mins = (time.time() - t0) / 60
            print(f"[{qi}/{len(queries)}] {q}: открыто фирм {got or 0} (всего {len(items)}, {mins:.1f} мин)", flush=True)
            RAW.write_text(json.dumps(items, ensure_ascii=False), encoding="utf-8")
            if got is not None:
                done.add(q)
                DONE.write_text(json.dumps(sorted(done), ensure_ascii=False), encoding="utf-8")
            live.flush()
            write_xlsx(build_firms(items), quiet=True)  # Excel всегда актуален, даже если прервётся
        live.flush()
        br.close()
    return items


