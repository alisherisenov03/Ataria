CITY = "Экибастуз"
# грубая рамка города (без сёл администрации), используется только если у фирмы нет adm_div
BBOX = (51.66, 75.22, 51.79, 75.43)  # lat_min, lon_min, lat_max, lon_max
BASE = "https://2gis.kz/ekibastuz"


def base_id(i):
    return str(i).split("_")[0]


def in_ekibastuz(it):
    divs = it.get("adm_div") or []
    if any(d.get("type") == "settlement" for d in divs):
        return False  # сёла городской администрации — не сам город
    cities = [d.get("name", "") for d in divs if d.get("type") == "city"]
    if cities:
        return CITY in cities
    txt = " ".join(str(it.get(k, "")) for k in ("full_name", "full_address_name", "address_name"))
    if CITY in txt:
        return True
    p = it.get("point") or {}
    if "lat" in p and "lon" in p:
        return BBOX[0] <= p["lat"] <= BBOX[2] and BBOX[1] <= p["lon"] <= BBOX[3]
    return False


def wait_captcha(page):
    if "captcha" in page.url:
        print("\n>>> 2ГИС показал капчу. Пройдите её в окне браузера — жду до 10 минут...", flush=True)
        for _ in range(600):
            time.sleep(1)
            if "captcha" not in page.url:
                print(">>> Капча пройдена, продолжаю.", flush=True)
                time.sleep(2)
                return
        sys.exit("Капча не пройдена за 10 минут.")


