def rubrics_report(items, path=HERE / "rubrics_report.csv"):
    """Все рубрики, встреченные в собранных фирмах: сколько фирм и какой ОКЭД присвоен.
    Нужен, чтобы поправить таблицу RUBRIC_MAP без повторного сбора."""
    import csv
    from collections import Counter
    cnt, okv = Counter(), {}
    for it in items.values():
        if not in_ekibastuz(it):
            continue
        for rn in rubric_names(it)[:1]:
            cnt[rn] += 1
            m = next((m for m in RUBRIC_MAP if re.search(m[2], rn.lower())), None)
            okv[rn] = f"{m[3]} ({', '.join(programs_for(m[3])) or 'не входит'})" if m else ""
    try:
        with open(path, "w", encoding="utf-8-sig", newline="") as f:
            w = csv.writer(f, delimiter=";")
            w.writerow(["Рубрика 2ГИС (основная)", "Фирм", "ОКЭД (программа)"])
            for rn, n in cnt.most_common():
                w.writerow([rn, n, okv[rn]])
        print(f"Отчёт по рубрикам: {path.name} ({len(cnt)} рубрик)")
    except PermissionError:
        print(f"! {path.name} открыт в Excel — отчёт не записан")


def write_xlsx(rows, path=XLSX, quiet=False):
    from openpyxl import Workbook
    from openpyxl.styles import Font, PatternFill, Alignment
    from openpyxl.utils import get_column_letter

    wb = Workbook()

    def sheet(ws, header, data, widths):
        ws.append(header)
        for r in data:
            ws.append(r)
        for c in ws[1]:
            c.font = Font(bold=True, color="FFFFFF")
            c.fill = PatternFill("solid", fgColor="1F6F43")
            c.alignment = Alignment(vertical="center", wrap_text=True)
        for i, w in enumerate(widths, 1):
            ws.column_dimensions[get_column_letter(i)].width = w
        ws.freeze_panes = "A2"
        ws.auto_filter.ref = f"A1:{get_column_letter(len(header))}{max(ws.max_row, 2)}"

    ws = wb.active
    ws.title = "Фирмы"
    sheet(ws, ["Название", "Рубрика", "ОКЭД", "Программа", "Адрес", "Телефон", "WhatsApp",
               "сайт/Instagram", "Ссылка 2ГИС"], rows, [34, 30, 40, 34, 36, 30, 26, 44, 42])
    for r in range(2, ws.max_row + 1):
        for col in (7, 9):
            c = ws.cell(r, col)
            if c.value:
                c.hyperlink = c.value
                c.font = Font(color="0563C1", underline="single")

    ok = []
    for c, n in ISKER:
        ok.append([c, n, P_ISKER, SRC_ISKER_ADILET])
    for c, n in ISKER_EXCL:
        ok.append([c, n, f"{P_ISKER} — ИСКЛЮЧЁН", SRC_ISKER_ADILET])
    for c, n in ISKER_MIO:
        ok.append([c, n, P_ISKER_MIO, SRC_ISKER_MIO])
    for c, n, sec in ORLEU:
        ok.append([c, f"{n} [{sec}]", P_ORLEU, SRC_ORLEU])
    for c, n in ORLEU_EXCL:
        ok.append([c, n, f"{P_ORLEU} — ИСКЛЮЧЁН", SRC_ORLEU])
    sheet(wb.create_sheet("ОКЭД"), ["Код", "Название", "Программа", "Источник"], ok, [10, 70, 32, 70])

    mp = []
    for label, qs, rx, code, cname in RUBRIC_MAP:
        progs = programs_for(code)
        mp.append([label, f"{code} {cname}", ", ".join(progs) if progs else "не входит — отсеивается"])
    sheet(wb.create_sheet("Соответствие"), ["Рубрика 2ГИС", "ОКЭД", "Программа"], mp, [48, 60, 50])

    try:
        wb.save(path)
    except PermissionError:
        if not quiet:
            print(f"! {path.name} открыт в Excel — закройте его и запустите rebuild_excel.bat")
        return
    if not quiet:
        print(f"Excel: {path}  (фирм: {len(rows)})")


